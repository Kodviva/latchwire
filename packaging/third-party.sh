#!/bin/sh
# Lists the third-party code in the shipped binaries.
#
#   packaging/third-party.sh --write          rewrites packaging/THIRD_PARTY.md
#   packaging/third-party.sh --check          fails when that file is stale
#   packaging/third-party.sh --licenses FILE  writes every licence text, for
#                                             the packages
#
# The modules come from go list -deps for every release platform. A module
# missing from the table below stops this script: read its licence, then add
# it. Apache-2.0, BSD and MIT all ask for their text to ship with binaries.
set -eu

root=$(cd "$(dirname "$0")/.." && pwd)
cd "$root"
export GOFLAGS=-mod=readonly

# module|SPDX|licence file(s) relative to the module|where it is used
table() {
	cat <<'TABLE'
github.com/go-piv/piv-go/v2|Apache-2.0 AND BSD-3-Clause|LICENSE third_party/rsa/LICENSE|Vendored and patched in third_party/piv-go, see PATCHES.md there
github.com/google/jsonschema-go|MIT|LICENSE|Go module, used by the MCP SDK
github.com/modelcontextprotocol/go-sdk|Apache-2.0 AND MIT|LICENSE|Go module, latchwire mcp
github.com/segmentio/asm|MIT-0|LICENSE|Go module, used by the MCP SDK
github.com/segmentio/encoding|MIT|LICENSE|Go module, used by the MCP SDK
github.com/yosida95/uritemplate/v3|BSD-3-Clause|LICENSE|Go module, used by the MCP SDK
golang.org/x/crypto|BSD-3-Clause|LICENSE|Go module
golang.org/x/net|BSD-3-Clause|LICENSE|Go module
golang.org/x/oauth2|BSD-3-Clause|LICENSE|Go module, used by the MCP SDK
golang.org/x/sync|BSD-3-Clause|LICENSE|Go module, used by the MCP SDK
golang.org/x/sys|BSD-3-Clause|LICENSE|Go module
golang.org/x/term|BSD-3-Clause|LICENSE|Go module
golang.org/x/time|BSD-3-Clause|LICENSE|Go module
golang.zx2c4.com/wireguard|MIT|LICENSE|Vendored and patched in third_party/wireguard-go, see PATCHES.md there
golang.zx2c4.com/wintun|MIT|LICENSE|Go module, Windows only
TABLE
}

# modules prints the third-party modules of all release platforms, sorted.
modules() {
	for goos in linux darwin windows; do
		GOOS=$goos CGO_ENABLED=1 go list -deps -f '{{with .Module}}{{if not .Main}}{{.Path}}{{end}}{{end}}' ./cmd/latchwire
	done | LC_ALL=C sort -u
}

lookup() { table | grep "^$1|" || { echo "third-party.sh: $1 is not in the table: read its licence, then add it" >&2; exit 1; }; }

# version MODULE prints what a replaced module's copy is based on.
version() {
	case $1 in
	github.com/go-piv/piv-go/v2) sed -n 's/^Base: .*\*\*\(v[0-9.]*\)\*\*.*/\1/p' third_party/piv-go/PATCHES.md ;;
	golang.zx2c4.com/wireguard) sed -n 's/^Base: .*commit `\([0-9a-f]\{12\}\).*/\1/p' third_party/wireguard-go/PATCHES.md ;;
	*) go list -m -f '{{.Version}}' "$1" ;;
	esac
}

markdown() {
	cat <<'HEAD'
# Third-party code

Generated by `packaging/third-party.sh --write`; CI fails when it is stale.
These are the modules linked into `latchwire` on Linux, macOS or Windows.
Test-only dependencies are not listed. The packages carry the full licence
texts in `THIRD_PARTY_LICENSES.txt`.

| Module | Version | Licence | Origin |
| --- | --- | --- | --- |
HEAD
	for m in $(modules); do
		line=$(lookup "$m") || exit 1
		spdx=$(echo "$line" | cut -d'|' -f2)
		origin=$(echo "$line" | cut -d'|' -f4)
		echo "| \`$m\` | $(version "$m") | $spdx | $origin |"
	done
	cat <<'TAIL'

Also in the binaries or next to them:

| Component | Licence | How |
| --- | --- | --- |
| Go standard library and runtime | BSD-3-Clause | Linked statically |
| PCSC lite (`libpcsclite`, Linux) | BSD-3-Clause | Linked dynamically, from the distribution |
| `PCSC.framework` (macOS) | Apple system component | Linked dynamically, part of macOS |
TAIL
}

licenses() {
	cat <<'HEAD'
Licences of the third-party code in Latchwire. See THIRD_PARTY.md in the
source for what is used where.
HEAD
	section() {
		printf '\n================================================================\n%s\n================================================================\n\n' "$1"
		cat "$2"
	}
	section "Go standard library and runtime" "$(go env GOROOT)/LICENSE"
	for m in $(modules); do
		line=$(lookup "$m") || exit 1
		dir=$(go list -m -f '{{.Dir}}' "$m")
		for f in $(echo "$line" | cut -d'|' -f3); do
			section "$m ($f)" "$dir/$f"
		done
	done
}

case ${1:-} in
--write) markdown >packaging/THIRD_PARTY.md ;;
--check)
	tmp=$(mktemp)
	trap 'rm -f "$tmp"' EXIT
	markdown >"$tmp"
	diff -u packaging/THIRD_PARTY.md "$tmp" || { echo "third-party.sh: packaging/THIRD_PARTY.md is stale, run: packaging/third-party.sh --write" >&2; exit 1; }
	;;
--licenses) licenses >"${2:?--licenses needs a file}" ;;
*) echo "usage: third-party.sh --write | --check | --licenses FILE" >&2; exit 2 ;;
esac
