package icu

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"regexp"
	"strconv"
	"strings"
)

// Entry is one message of an ARB file.
type Entry struct {
	ID      string
	Text    string
	Message Message
	// Description, Section and Verbs come from the "@ID" object. Verbs maps
	// a placeholder to its printf verb ("%q", "%d", "%02x", "%v", "%w").
	// Section is a heading: the constants from this entry on form one block.
	Description string
	Section     string
	Verbs       map[string]string
}

// Verb is the printf verb of a placeholder; %s unless the file says otherwise.
func (e *Entry) Verb(name string) string {
	if v := e.Verbs[name]; v != "" {
		return v
	}
	return "%s"
}

// File is a parsed ARB file. Entries keep the file's order, which is the
// order of the generated constants.
type File struct {
	Locale  string
	Attrs   map[string]string // other "@@" attributes
	Entries []*Entry
	ByID    map[string]*Entry
}

type metadata struct {
	Description  string `json:"description"`
	Section      string `json:"section"`
	Placeholders map[string]struct {
		Verb string `json:"verb"`
	} `json:"placeholders"`
}

// ParseARB reads an ARB file. Duplicate keys are errors: encoding/json would
// silently keep the last one.
func ParseARB(data []byte) (*File, error) {
	dec := json.NewDecoder(bytes.NewReader(data))
	tok, err := dec.Token()
	if err != nil {
		return nil, err
	}
	if tok != json.Delim('{') {
		return nil, fmt.Errorf("arb: expected an object")
	}
	f := &File{Attrs: map[string]string{}, ByID: map[string]*Entry{}}
	metas := map[string]metadata{}
	seen := map[string]bool{}
	for dec.More() {
		tok, err := dec.Token()
		if err != nil {
			return nil, err
		}
		key := tok.(string)
		if seen[key] {
			return nil, fmt.Errorf("arb: duplicate key %s", key)
		}
		seen[key] = true
		switch {
		case strings.HasPrefix(key, "@@"):
			var v string
			if err := dec.Decode(&v); err != nil {
				return nil, fmt.Errorf("arb: %s: %w", key, err)
			}
			if key == "@@locale" {
				f.Locale = v
			} else {
				f.Attrs[key[2:]] = v
			}
		case strings.HasPrefix(key, "@"):
			var m metadata
			if err := dec.Decode(&m); err != nil {
				return nil, fmt.Errorf("arb: %s: %w", key, err)
			}
			metas[key[1:]] = m
		default:
			var v string
			if err := dec.Decode(&v); err != nil {
				return nil, fmt.Errorf("arb: %s: %w", key, err)
			}
			m, err := Parse(v)
			if err != nil {
				return nil, fmt.Errorf("arb: %s: %w", key, err)
			}
			e := &Entry{ID: key, Text: v, Message: m}
			f.Entries = append(f.Entries, e)
			f.ByID[key] = e
		}
	}
	for id, m := range metas {
		e := f.ByID[id]
		if e == nil {
			return nil, fmt.Errorf("arb: metadata for unknown message %s", id)
		}
		e.Description, e.Section = m.Description, m.Section
		if len(m.Placeholders) > 0 {
			e.Verbs = map[string]string{}
			for name, p := range m.Placeholders {
				e.Verbs[name] = p.Verb
			}
		}
	}
	return f, nil
}

// GoFormat turns a message without plural or select into a printf format.
// Arguments follow the order of first appearance. A placeholder used twice
// makes every verb explicit (%[1]s).
func GoFormat(e *Entry) (string, error) {
	if !e.Message.Plain() {
		return "", fmt.Errorf("%s: plural and select messages have no printf form", e.ID)
	}
	index := map[string]int{}
	repeated := false
	for _, n := range e.Message {
		if n.kind == nodeArg {
			if index[n.name] != 0 {
				repeated = true
				continue
			}
			index[n.name] = len(index) + 1
		}
	}
	var b strings.Builder
	for _, n := range e.Message {
		switch n.kind {
		case nodeText:
			if len(index) > 0 {
				b.WriteString(strings.ReplaceAll(n.text, "%", "%%"))
			} else {
				b.WriteString(n.text)
			}
		case nodeArg:
			v := e.Verb(n.name)
			if repeated {
				v = fmt.Sprintf("%%[%d]%s", index[n.name], v[1:])
			}
			b.WriteString(v)
		}
	}
	return b.String(), nil
}

const genHeader = `// Code generated by internal/msg/gen from locales/en.arb. DO NOT EDIT.

// Package msg holds user-facing message strings. The source of every string
// is locales/en.arb (ICU MessageFormat in an ARB file); see doc.go.
// Format strings never take secret values: keys and PINs are never echoed.
package msg
`

var uiID = regexp.MustCompile(`^UI[A-Z]`)

// GenerateGo produces en.go from the English catalog: one printf-format
// constant per message, and one ID constant per UI message (prefix UI),
// which only the desktop app renders.
func GenerateGo(f *File) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(genHeader)
	open := false
	closeBlock := func() {
		if open {
			b.WriteString(")\n")
			open = false
		}
	}
	for _, e := range f.Entries {
		if uiID.MatchString(e.ID) {
			continue
		}
		if e.Section != "" || !open {
			closeBlock()
			b.WriteString("\n")
			writeComment(&b, e.Section)
			b.WriteString("const (\n")
			open = true
		}
		s, err := GoFormat(e)
		if err != nil {
			return nil, err
		}
		writeComment(&b, e.Description)
		fmt.Fprintf(&b, "%s = %s\n", e.ID, goString(s))
	}
	closeBlock()
	b.WriteString("\n// Desktop app messages, rendered with Render.\nconst (\n")
	for _, e := range f.Entries {
		if uiID.MatchString(e.ID) {
			writeComment(&b, e.Description)
			fmt.Fprintf(&b, "%s ID = %q\n", e.ID, e.ID)
		}
	}
	b.WriteString(")\n")
	return format.Source(b.Bytes())
}

func writeComment(b *bytes.Buffer, s string) {
	if s == "" {
		return
	}
	for _, l := range strings.Split(s, "\n") {
		b.WriteString("// " + l + "\n")
	}
}

func goString(s string) string {
	if strings.Count(s, "\n") >= 3 && !strings.Contains(s, "`") {
		return "`" + s + "`"
	}
	return strconv.Quote(s)
}
